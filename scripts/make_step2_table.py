"""Step 2 table (calib split, fixed precisions) built ONLY from results/ (local-safe).

Selects runs through results/index.csv and fails loudly on missing, duplicate, smoke or
mixed-commit entries. Writes paper/tables/step2_calib_fixed.{csv,md,tex}.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

POLICIES = [("calib_fixed_pt_fp32", "PyTorch FP32 (ref.)", "pt_fp32"),
            ("calib_fixed_fp32", "TensorRT FP32", "fp32"),
            ("calib_fixed_fp16", "TensorRT FP16", "fp16"),
            ("calib_fixed_int8", "TensorRT INT8", "int8"),
            ("calib_oracle_cheap_dev", "Oracle-cheap (dev, uses GT)", None)]
SLICES = ("all", "easy", "crowded", "night")


class TableError(RuntimeError):
    pass


def load_index(results: Path) -> dict[str, dict]:
    rows = list(csv.DictReader(open(results / "index.csv", newline="", encoding="utf-8")))
    by: dict[str, dict] = {}
    for r in rows:
        if r["exp_id"] in by:
            raise TableError(f"duplicate index entry {r['exp_id']}")
        by[r["exp_id"]] = r
    return by


def build(results: Path) -> tuple[list[dict], dict]:
    idx = load_index(results)
    need = [p[0] for p in POLICIES] + ["microbench_yolo11s", "engines_yolo11s", "sanity_02_yolo11s"]
    missing = [e for e in need if e not in idx]
    if missing:
        raise TableError(f"missing runs in index.csv: {missing}")
    sel = {e: idx[e] for e in need}
    if any(r["smoke"] == "True" for r in sel.values()):
        raise TableError("a selected run is a SMOKE run")
    commits = {r["git_commit"] for r in sel.values()}
    if len(commits) != 1:
        raise TableError(f"runs come from different commits: {commits}")
    if any(r["split"] != "calib" for r in sel.values()):
        raise TableError("Step 2 table must contain calib-split runs only")

    mb = json.loads((results / sel["microbench_yolo11s"]["path"] / "microbench.json").read_text())["per_backend"]
    eng = json.loads((results / sel["engines_yolo11s"]["path"] / "engines.json").read_text())
    san = json.loads((results / sel["sanity_02_yolo11s"]["path"] / "sanity.json").read_text())
    rows, n_frames = [], {}
    for exp_id, label, backend in POLICIES:
        m = json.loads((results / sel[exp_id]["path"] / "metrics.json").read_text())
        r = {"policy": label}
        for s in SLICES:
            r[f"map50_95_{s}"] = 100 * m[s]["map50_95"]
            n_frames[s] = m[s]["n_images"]
        r["map50_all"] = 100 * m["all"]["map50"]
        r["mean_f1_05"] = m["all"]["mean_f1_05"]
        r["frac_int8"] = m["all"]["frac_level"].get("int8", 0.0)
        r["engine_ms_median"] = mb[backend]["infer_ms"]["median"] if backend else None
        r["engine_ms_p95"] = mb[backend]["infer_ms"]["p95"] if backend else None
        r["engine_MB"] = eng[backend]["bytes"] / 1e6 if backend in eng else None
        rows.append(r)
    meta = {"git_commit": commits.pop(), "n_frames": n_frames, "sanity_all_pass": san["all_pass"],
            "sanity": san["checks"]}
    return rows, meta


def _f(v, nd=2):
    return "–" if v is None else f"{v:.{nd}f}"


COLS = [("policy", "Policy", None), ("map50_95_all", "mAP50-95", 2), ("map50_all", "mAP50", 2),
        ("map50_95_easy", "easy", 2), ("map50_95_crowded", "crowded", 2), ("map50_95_night", "night", 2),
        ("mean_f1_05", "mean F1@.5", 3), ("frac_int8", "INT8 frac.", 2), ("engine_ms_median", "engine ms (med)", 2),
        ("engine_ms_p95", "engine ms (p95)", 2), ("engine_MB", "engine MB", 1)]


def write(rows: list[dict], meta: dict, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "step2_calib_fixed.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    n = meta["n_frames"]
    caption = (f"Calib split only (20 clips, {n['all']} frames; easy {n['easy']}, crowded {n['crowded']}, "
               f"night {n['night']}). mAP in points (pycocotools, maxDets 300). Engine latency: Ultralytics "
               f"inference time on one pre-decoded frame, T4, median/p95 of 300 runs (microbench, not the "
               f"Step 4 protocol). Oracle uses GT and is not deployable. Generated from results/ at commit "
               f"{meta['git_commit'][:8]}.")
    md = ["| " + " | ".join(c[1] for c in COLS) + " |", "|" + "---|" * len(COLS)]
    for r in rows:
        md.append("| " + " | ".join(r[k] if nd is None else _f(r[k], nd) for k, _, nd in COLS) + " |")
    (out / "step2_calib_fixed.md").write_text("\n".join(md) + "\n\n" + caption + "\n", encoding="utf-8")
    tex = ["% generated by scripts/make_step2_table.py -- do not edit", "\\begin{table}[t]", "\\centering",
           f"\\caption{{{caption}}}", "\\label{tab:step2-calib-fixed}", "\\small",
           "\\begin{tabular}{l" + "r" * (len(COLS) - 1) + "}", "\\toprule",
           " & ".join(c[1] for c in COLS) + " \\\\", "\\midrule"]
    for r in rows:
        tex.append(" & ".join(r[k] if nd is None else _f(r[k], nd).replace("–", "--") for k, _, nd in COLS) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (out / "step2_calib_fixed.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "results"))
    ap.add_argument("--out", default=str(REPO / "paper" / "tables"))
    a = ap.parse_args()
    rows, meta = build(Path(a.results))
    write(rows, meta, Path(a.out))
    print((Path(a.out) / "step2_calib_fixed.md").read_text(encoding="utf-8"))
    print("sanity all_pass:", meta["sanity_all_pass"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
