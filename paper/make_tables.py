OUT = HERE / "tables"
P = "r04_test_"
POLICY_LABEL = {"fixed_fp32": "Fixed FP32", "fixed_fp16": "Fixed FP16", "fixed_int8": "Fixed INT8",
                "adaptive_main": "Adaptive (locked)", "random_matched": "Matched random (10 seeds)",
                "random_iid": "i.i.d. random (10 seeds)", "oracle_cheap": "Oracle-cheap (uses GT)"}
