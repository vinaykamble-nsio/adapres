ABLATION_DESC = {
    "A-m": "leave out motion", "A-c": "leave out clutter", "A-n": "leave out count", "A-u": "leave out uncertainty",
    "A-s": "leave out scene-change cue", "S-m": "motion only", "S-c": "clutter only", "S-n": "count only",
    "S-u": "uncertainty only", "S-s": "scene-change cue only", "A-hyst": "no persistence (K = 1)",
    "A-sc-override": "scene-change override off", "A-asym": "asymmetric persistence (K_up = 1)",
    "A-ema": "no EMA (alpha = 1)"}


def pts(x):
    return None if x is None else 100.0 * x


def fmt(v, nd=2):
    if v is None:
        return "–"
    if isinstance(v, str):
        return v
    return f"{v:.{nd}f}"


def ci(c, nd=2):
    return "–" if not c else f"[{100 * c[0]:.{nd}f}, {100 * c[1]:.{nd}f}]"


def tex_escape(s: str) -> str:
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#").replace("–", "--").replace("±", "$\\pm$").replace("δ", "$\\delta$")
            .replace("θ", "$\\theta$").replace("α", "$\\alpha$").replace("†", "$^\\dagger$"))


def write_table(name: str, cols: list[tuple[str, str]], rows: list[dict], caption: str, label: str,
                raw: list[dict] | None = None, out: Path = OUT) -> None:
    """cols: (key, header). rows: formatted strings per key. raw: unformatted values for the csv."""
    out.mkdir(parents=True, exist_ok=True)
    with open(out / f"{name}.csv", "w", newline="", encoding="utf-8") as f:
        data = raw if raw is not None else rows
        fields = list(dict.fromkeys(k for row in data for k in row))  # union of keys, first-seen order
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(data)
    md = ["| " + " | ".join(h for _, h in cols) + " |", "|" + "---|" * len(cols)]
    md += ["| " + " | ".join(str(r[k]).replace("|", "\\|") for k, _ in cols) + " |" for r in rows]
    (out / f"{name}.md").write_text("\n".join(md) + "\n\n" + caption + "\n", encoding="utf-8")
    tex = ["% generated by paper/make_tables.py from results/ -- do not edit", "\\begin{table}[t]", "\\centering",
           f"\\caption{{{tex_escape(caption)}}}", f"\\label{{{label}}}", "\\scriptsize",
           "\\begin{tabular}{l" + "r" * (len(cols) - 1) + "}", "\\toprule",
           " & ".join(tex_escape(h) for _, h in cols) + " \\\\", "\\midrule"]
    tex += [" & ".join(tex_escape(str(r[k])) for k, _ in cols) + " \\\\" for r in rows]
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (out / f"{name}.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")


def build(results: Path = RESULTS, out: Path = OUT) -> dict:
    idx = index(results)
    commit = r04_commit(results, idx)
    M = {p: load(P + p, "metrics.json", results, idx) for p in MAIN_POLICIES}
    boot = load(P + "bootstrap", "bootstrap.json", results, idx)
    energy = load(P + "energy_latency", "energy.json", results, idx)
    mem = load(P + "energy_latency", "memory.json", results, idx)
    live = load(P + "energy_latency", "live_validation.json", results, idx)
    cal = load("r04_calibration", "calibration.json", results, idx)
    hyp = load("r04_test_hypotheses_v2", "hypotheses.json", results, idx)
    stages = json.loads((results / "r04_stages" / "stages.json").read_text())
    n = M["fixed_fp16"]
    made = {}

    # ---- T1 main test table
    rows, raw = [], []
    for p in MAIN_POLICIES:
        m = M[p]
        a = m["all"]
        sd = a.get("map50_95_sd")
        rows.append({"policy": POLICY_LABEL[p],
                     "map": fmt(pts(a["map50_95"])) + ("" if sd is None else f" ± {100 * sd:.2f}"),
                     "map_ci": ci(a.get("map50_95_ci")), "map50": fmt(pts(a["map50"])),
                     "easy": fmt(pts(m["easy"]["map50_95"])), "crowded": fmt(pts(m["crowded"]["map50_95"])),
                     "night": fmt(pts(m["night"]["map50_95"])),
                     "scene": fmt(pts(m.get("scene_change", {}).get("map50_95"))),
                     "int8": fmt(a["frac_level"]["int8"]), "sw": fmt(a.get("switch_rate_per_100"))})
        raw.append({"policy": p, "map50_95": a["map50_95"], "map50_95_sd": sd,
                    "map50_95_ci_lo": (a.get("map50_95_ci") or [None, None])[0],
                    "map50_95_ci_hi": (a.get("map50_95_ci") or [None, None])[1], "map50": a["map50"],
                    **{f"map50_95_{s}": m.get(s, {}).get("map50_95") for s in ("easy", "crowded", "night", "scene_change")},
                    "frac_int8": a["frac_level"]["int8"], "switch_rate_per_100": a.get("switch_rate_per_100")})
    cap = (f"Test split (40 clips, {n['all']['n_images']} frames; easy {n['easy']['n_images']}, crowded "
           f"{n['crowded']['n_images']}, night {n['night']['n_images']}; scene-change† {n['scene_change']['n_images']} "
           f"frames of {M['fixed_fp16']['streams_all']['n_images']} in 20 spliced streams). mAP in points "
           f"(pycocotools, single-label predict outputs); 95% cluster-bootstrap CI over clips "
           f"({boot['n_resamples']} resamples); random policies: mean ± SD over 10 seeds. "
           "†Scene changes are synthetic (spliced clips). Generated from results/ at commit " + commit[:8] + ".")
    write_table("test_main", [("policy", "Policy"), ("map", "mAP50-95"), ("map_ci", "95% CI"), ("map50", "mAP50"),
                              ("easy", "easy"), ("crowded", "crowded"), ("night", "night"), ("scene", "scene-chg.†"),
                              ("int8", "INT8 frac."), ("sw", "switches/100")], rows, cap, "tab:test-main", raw, out)
    made["test_main"] = len(rows)

    # ---- T2 measured latency / energy (E_total primary, E_dyn secondary)
    s = energy["summary"]
    order = ["fixed_fp32", "fixed_fp16", "fixed_int8", "adaptive_sequential", "adaptive_pipelined"]
    lab = {"fixed_fp32": "Fixed FP32", "fixed_fp16": "Fixed FP16", "fixed_int8": "Fixed INT8",
           "adaptive_sequential": "Adaptive, sequential cues", "adaptive_pipelined": "Adaptive, pipelined cues"}

    def rng(d, nd=2):
        return "–" if not d else f"{d['median']:.{nd}f} [{d['min']:.{nd}f}–{d['max']:.{nd}f}]"

    rows, raw = [], []
    for k in order:
        v = s[k]
        rows.append({"cfg": lab[k], "lat": rng(v["latency_total_ms_median"]), "p95": fmt(v["latency_total_ms_p95"]["median"]),
                     "fps": fmt(v["throughput_fps"]["median"], 1), "etot": rng(v["E_total_mJ_per_frame"], 1),
                     "edyn": rng(v["E_dyn_mJ_per_frame"], 1), "pw": fmt(v["mean_power_W"]["median"], 1),
                     "int8": fmt(v.get("frac_int8"))})
        raw.append({"config": k, **{f"{m}_{q}": (v[m] or {}).get(q) for m in ("latency_total_ms_median",
                    "E_total_mJ_per_frame", "E_dyn_mJ_per_frame", "throughput_fps", "mean_power_W") for q in ("median", "min", "max")},
                    "latency_p95_ms": v["latency_total_ms_p95"]["median"], "frac_int8": v.get("frac_int8")})
    cap = (f"Measured on one Tesla T4 (live, frames pre-decoded), {energy['repeats']} interleaved repeats of "
           f"≥{energy['measure_s']:.0f} s after ≥{energy['warmup_s']:.0f} s warm-up; median [min–max] over repeats. "
           f"Energy from the NVML board energy counter ({energy['method']}): E_total/frame is primary; "
           f"E_dyn/frame = (ΔE − P_idle·T)/N is secondary (idle-subtraction favours configurations that leave the GPU "
           f"waiting, see DEVIATIONS.md V1). GPU board energy only.")
    write_table("test_energy_latency", [("cfg", "Configuration"), ("lat", "latency ms (median)"), ("p95", "p95 ms"),
                                        ("fps", "fps"), ("etot", "E_total mJ/frame"), ("edyn", "E_dyn mJ/frame"),
                                        ("pw", "power W"), ("int8", "INT8 frac.")], rows, cap, "tab:energy", raw, out)
    made["test_energy_latency"] = len(rows)

    # ---- T3 bootstrap pairs
    rows, raw = [], []
    full = {**M, "adaptive_ksweep1": load(f"{P}adaptive_ksweep1", "metrics.json", results, idx)}
    for k, v in boot["pairs"].items():
        a_, b_ = [x.strip() for x in k.split(" - ")]
        name = f"{POLICY_LABEL.get(a_, a_)} − {POLICY_LABEL.get(b_, b_)}".replace("adaptive_ksweep1", "Adaptive K=1")
        x, y = v["map50_95"], v["map50"]
        pt = {m: full[a_]["all"][m] - full[b_]["all"][m] for m in ("map50_95", "map50")}
        rows.append({"pair": name, "p": fmt(pts(pt["map50_95"]), 3), "d": fmt(pts(x["mean"]), 3), "ci": ci(x["ci95"], 3),
                     "ex": "yes" if x["excludes_zero"] else "no", "p50": fmt(pts(pt["map50"]), 3), "ci50": ci(y["ci95"], 3)})
        raw.append({"pair": k, "map50_95_point": pt["map50_95"], "map50_95_boot_mean": x["mean"],
                    "map50_95_ci_lo": x["ci95"][0], "map50_95_ci_hi": x["ci95"][1], "excludes_zero": x["excludes_zero"],
                    "map50_point": pt["map50"], "map50_boot_mean": y["mean"], "map50_ci_lo": y["ci95"][0],
                    "map50_ci_hi": y["ci95"][1]})
    cap = (f"Paired differences on the test split (points): full-data point estimate, bootstrap mean and 95% "
           f"cluster-bootstrap CI over the 40 clips ({boot['n_resamples']} resamples, seed {boot['seed']}); random "
           f"groups use the per-resample mean over 10 seeds. Adaptive − K=1 is identically 0 because the locked "
           f"controller has K = 1.")
    write_table("test_ci_pairs", [("pair", "Difference"), ("p", "Δ mAP50-95"), ("d", "boot. mean"), ("ci", "95% CI"),
                                  ("ex", "excludes 0"), ("p50", "Δ mAP50"), ("ci50", "95% CI")], rows, cap,
                "tab:ci-pairs", raw, out)
    made["test_ci_pairs"] = len(rows)

    # ---- T4 ablations (+ delta-Pareto locks)
    main_map = M["adaptive_main"]["all"]["map50_95"]
    rows, raw = [], []
    for k in sorted(x for x in idx if x.startswith(P + "adaptive_abl_")) + \
            sorted(x for x in idx if x.startswith(P + "adaptive_delta")):
        name = k[len(P + "adaptive_"):]
        a = load(k, "metrics.json", results, idx)["all"]
        lk = cal["locks"].get(name, {})
        short = name[4:] if name.startswith("abl_") else name
        desc = ABLATION_DESC.get(short, f"locked at δ = {name[5:]} pts" if name.startswith("delta") else "")
        rows.append({"id": short, "desc": desc, "map": fmt(pts(a["map50_95"])),
                     "d": fmt(pts(a["map50_95"] - main_map), 2), "int8": fmt(a["frac_level"]["int8"]),
                     "sw": fmt(a["switch_rate_per_100"]), "cal": "feasible" if lk.get("status") == "feasible" else
                     ("infeasible" if lk.get("status") else "–")})
        raw.append({"id": name, "map50_95": a["map50_95"], "delta_vs_main": a["map50_95"] - main_map,
                    "frac_int8": a["frac_level"]["int8"], "switch_rate_per_100": a["switch_rate_per_100"],
                    "calib_status": lk.get("status"), "lock_sha256": lk.get("hash")})
    cap = ("Ablations on the test split. Each variant was re-calibrated on calib with the same procedure and locked "
           "before test (δ = 0.5 pts); δ rows are the Pareto locks. Δ vs the locked main controller, in points.")
    write_table("test_ablations", [("id", "ID"), ("desc", "Variant"), ("map", "mAP50-95"), ("d", "Δ vs main"),
                                   ("int8", "INT8 frac."), ("sw", "switches/100"), ("cal", "calib")], rows, cap,
                "tab:ablations", raw, out)
    made["test_ablations"] = len(rows)

    # ---- T5 K-sweep (sensitivity analysis)
    ks = sorted(int(k[len(P + "adaptive_ksweep"):]) for k in idx if k.startswith(P + "adaptive_ksweep"))
    k1 = load(f"{P}adaptive_ksweep1", "metrics.json", results, idx)["all"]
    rows, raw = [], []
    for K in ks:
        a = load(f"{P}adaptive_ksweep{K}", "metrics.json", results, idx)["all"]
        rows.append({"K": str(K), "map": fmt(pts(a["map50_95"])), "d": fmt(pts(a["map50_95"] - k1["map50_95"]), 3),
                     "sw": fmt(a["switch_rate_per_100"]), "int8": fmt(a["frac_level"]["int8"])})
        raw.append({"K": K, "map50_95": a["map50_95"], "delta_vs_K1": a["map50_95"] - k1["map50_95"],
                    "switch_rate_per_100": a["switch_rate_per_100"], "frac_int8": a["frac_level"]["int8"]})
    cap = ("Sensitivity analysis (H3): persistence K varied with θ fixed at the locked value (no re-calibration), "
           "test split. The locked controller uses K = " + str(hyp["H3"]["locked_K"]) + ".")
    write_table("test_ksweep", [("K", "K"), ("map", "mAP50-95"), ("d", "Δ vs K=1"), ("sw", "switches/100"),
                                ("int8", "INT8 frac.")], rows, cap, "tab:ksweep", raw, out)
    made["test_ksweep"] = len(rows)

    # ---- T6 calibration / locked config
    L = cal["locks"]["main"]
    p = L["params"]
    rows = [{"k": "configurations searched (Stage A)", "v": str(cal["n_stage_a_configs"])},
            {"k": "configurations scored with mAP (Stage B)", "v": str(len(cal["stage_b_evaluated"]))},
            {"k": "status (calib)", "v": L["status"]},
            {"k": "FP16 calib mAP50-95", "v": fmt(pts(cal["fp16_calib_map50_95"]))},
            {"k": "locked calib mAP50-95", "v": fmt(pts(L["map50_95"]))},
            {"k": "calib drop vs FP16 (pts; δ = 0.5)", "v": fmt(pts(cal["fp16_calib_map50_95"] - L["map50_95"]))},
            {"k": "weights (m, c, n, u, s)", "v": ", ".join(fmt(p["weights"][x]) for x in "mcnus")},
            {"k": "θ / α / θ_sc / K_up / K_down / H", "v": f"{p['theta']:.4f} / {p['alpha']} / {p['theta_sc']} / "
                                                          f"{p['K_up']} / {p['K_down']} / {p['H']}"},
            {"k": "calib INT8 fraction / switches per 100", "v": f"{L['frac_int8']:.3f} / {L['switch_rate_per_100']:.2f}"},
            {"k": "engine latency INT8 / FP16 (ms, microbench)", "v": f"{cal['engine_ms']['int8']:.3f} / {cal['engine_ms']['fp16']:.3f}"},
            {"k": "switch penalty (ms)", "v": fmt(cal["switch_penalty_ms"], 3)},
            {"k": "sequential cue cost (ms/frame)", "v": fmt(cal["ctrl_overhead_ms_sequential"], 3)},
            {"k": "locked config SHA-256", "v": L["hash"][:16] + "…"}]
    cap = ("Calibration on the calib split only (PLAN §3.5) and the locked main configuration. The lock sat at the "
           "δ limit on calib and did not hold on test (limitation, DEVIATIONS.md L1).")
    write_table("calibration", [("k", "Item"), ("v", "Value")], rows, cap, "tab:calibration", None, out)
    made["calibration"] = len(rows)

    # ---- T7 hypotheses (revision 2)
    H1, H2, H3, H4 = hyp["H1"], hyp["H2"], hyp["H3"], hyp["H4"]
    yn = {True: "supported", False: "not supported", None: "–"}
    rows = [{"h": "H1", "c": f"mAP within δ = {H1['delta_pts']} pts of FP16, and lower latency and E_total than FP16",
             "v": f"drop {H1['map_drop_pts']:.2f} pts; pipelined: latency {H1['measured']['pipelined']['latency_median_ms']:.2f} vs "
                  f"{H1['measured']['pipelined']['fp16_latency_median_ms']:.2f} ms, E_total "
                  f"{H1['measured']['pipelined']['E_total_mJ_per_frame']:.1f} vs {H1['measured']['pipelined']['fp16_E_total_mJ_per_frame']:.1f} mJ",
             "r": f"{yn[H1['supported_pipelined']]} (pipelined), {yn[H1['supported_sequential']]} (sequential)"},
            {"h": "H2", "c": "adaptive − matched random: 95% CI excludes 0 (> 0)",
             "v": f"{H2['diff_mean_pts']:+.3f} pts (bootstrap mean), CI [{H2['diff_ci95_pts'][0]:+.3f}, {H2['diff_ci95_pts'][1]:+.3f}]",
             "r": yn[H2["supported"]]},
            {"h": "H3 (sensitivity)", "c": "every K ≥ 2: fewer switches than K = 1 and |Δ mAP| < 0.3 pts",
             "v": "; ".join(f"K={K}: {v['switch_rate']:.2f} vs {v['switch_rate_K1']:.2f}/100, {v['map_change_pts_vs_K1']:+.3f}"
                            for K, v in H3["per_K"].items()), "r": yn[H3["supported"]]},
            {"h": "H4", "c": "FP16 more often on night/crowded/scene-change than easy; > 50% of saving from easy",
             "v": "FP16 frac: " + ", ".join(f"{k} {v:.3f}" for k, v in H4["frac_fp16_by_slice"].items()) +
                  f"; easy share {H4['saving_share_from_easy']:.3f}", "r": yn[H4["supported"]]}]
    cap = ("Pre-registered hypotheses on the test split, evaluated mechanically (revision 2: E_total primary; H3 on "
           "the K-sweep as a sensitivity analysis; H4 engine-latency-only saving share; DEVIATIONS.md V1–V3). "
           "Revision 1 (r04_test_hypotheses) is superseded.")
    write_table("hypotheses", [("h", "Hypothesis"), ("c", "Criterion"), ("v", "Value"), ("r", "Result")], rows, cap,
                "tab:hypotheses", None, out)
    made["hypotheses"] = len(rows)

    # ---- T8 provenance, drift, memory
    drift = {c["check"].split()[1]: max(c["detail"].values()) for c in stages["1_engines_calib_cache"]["checks"]
             if c["check"].startswith("rebuilt")}
    meta = load(P + "adaptive_main", "meta.json", results, idx)
    pk = meta["env"]["packages"]
    eng = load("r04_engines_yolo11s", "engines.json", results, idx)
    rows = [{"k": "BDD subsets (Step 1)", "v": idx["bdd_subsets"]["git_commit"][:8]},
            {"k": "Step 2 eval / 02b diagnostic", "v": f"{idx['calib_fixed_fp16']['git_commit'][:8]} / {idx['val_diag_02b_yolo11s']['git_commit'][:8]}"},
            {"k": "Notebook 04 run (clean checkout)", "v": f"{commit[:8]} (dirty={meta['git_dirty']})"},
            {"k": "GPU / driver / CUDA", "v": f"{meta['env']['torch_cuda']['device0']} / "
                                             f"{meta['env']['nvidia_smi']['gpus'][0]['driver_version']} / {meta['env']['torch_cuda']['cuda_version']}"},
            {"k": "torch / ultralytics / tensorrt", "v": f"{pk['torch']} / {pk['ultralytics']} / {eng['fp16']['tensorrt']}"},
            {"k": "rebuilt-engine drift vs Step 2, calib mAP50-95 (max over slices, pts)",
             "v": ", ".join(f"{k} {v:.3f}" for k, v in drift.items())},
            {"k": "engine SHA-256 (FP32 / FP16 / INT8)", "v": " / ".join(eng[lv]["sha256"][:12] for lv in ("fp32", "fp16", "int8"))},
            {"k": "GPU memory, engine alone (MiB) FP32 / FP16 / INT8", "v": " / ".join(f"{mem['alone_delta_mib'][lv]:.0f}" for lv in ("fp32", "fp16", "int8"))},
            {"k": "GPU memory, adaptive set INT8+FP16 (MiB)", "v": f"{mem['adaptive_set_delta_mib']:.0f}"},
            {"k": "live vs replay (test subset): level agreement / |Δ mAP50-95| pts",
             "v": f"{live['level_agreement']:.3f} / {live['abs_diff_pts']['map50_95']:.3f} ({live['n_frames']} frames)"}]
    cap = "Provenance and measurement details (all values from results/)."
    write_table("provenance", [("k", "Item"), ("v", "Value")], rows, cap, "tab:provenance", None, out)
    made["provenance"] = len(rows)
    return made


if __name__ == "__main__":
    print(build())
